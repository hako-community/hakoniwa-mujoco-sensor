#!/usr/bin/env python3
"""Generate the RealSense bin-picking sample scene (RS-7).

Writes examples/realsense_binpicking/binpicking_scene.xml:
  - a cardboard bin (inner 0.40 x 0.30 m, 0.15 m high) on a concrete floor,
  - 30 free work pieces dropped from a grid above the bin (settle them with the
    physics before sensing): 12 aluminum shafts, 10 black-oxide blocks, 8 cast-iron parts,
  - the machine fixture (ground steel) with the sample pose ("見本荷姿") of one shaft,
  - cameras looking down: rs_bin (D435i, 0.75 m above the floor) and
    rs_near (D405, 0.40 m above the floor).

Material names follow config/realsense/materials.json (work_* / bin_* / floor* /
fixture*). Deterministic (fixed seed). Usage: python tools/gen_binpicking_scene.py
"""

import math
import os
import random

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "examples", "realsense_binpicking", "binpicking_scene.xml")


def quat_from_euler(rx, ry, rz):
    cx, sx = math.cos(rx / 2), math.sin(rx / 2)
    cy, sy = math.cos(ry / 2), math.sin(ry / 2)
    cz, sz = math.cos(rz / 2), math.sin(rz / 2)
    w = cx * cy * cz + sx * sy * sz
    x = sx * cy * cz - cx * sy * sz
    y = cx * sy * cz + sx * cy * sz
    z = cx * cy * sz - sx * sy * cz
    return w, x, y, z


def main():
    rng = random.Random(7)
    kinds = ["shaft"] * 12 + ["block"] * 10 + ["cast"] * 8
    rng.shuffle(kinds)
    bodies = []
    # 5 x 3 grid per layer, two layers, inside the bin footprint
    slots = [(-0.14 + 0.07 * i, -0.08 + 0.08 * j, 0.10 + 0.07 * k) for k in range(2) for j in range(3) for i in range(5)]
    for n, (kind, (x, y, z)) in enumerate(zip(kinds, slots)):
        x += rng.uniform(-0.01, 0.01)
        y += rng.uniform(-0.01, 0.01)
        q = quat_from_euler(rng.uniform(-math.pi, math.pi), rng.uniform(-math.pi, math.pi), rng.uniform(-math.pi, math.pi))
        quat = "%.5f %.5f %.5f %.5f" % q
        if kind == "shaft":
            geom = '<geom type="cylinder" size="0.012 0.03" material="work_alu_shaft"/>'
        elif kind == "block":
            geom = '<geom type="box" size="0.02 0.015 0.01" material="work_black_block"/>'
        else:
            geom = '<geom type="box" size="0.018 0.018 0.012" material="work_cast_part"/>'
        bodies.append(
            '    <body name="work_%02d_%s" pos="%.4f %.4f %.4f" quat="%s">\n'
            '      <freejoint/>\n      %s\n    </body>' % (n, kind, x, y, z, quat, geom))

    xml = f"""<mujoco model="realsense_binpicking">
  <!-- Generated by tools/gen_binpicking_scene.py (RS-7). Do not edit by hand. -->
  <option timestep="0.001"/>
  <visual><global offwidth="1920" offheight="1080"/></visual>
  <asset>
    <material name="floor_concrete" rgba="0.55 0.55 0.52 1"/>
    <material name="bin_card" rgba="0.62 0.47 0.30 1"/>
    <material name="work_alu_shaft" rgba="0.75 0.76 0.80 1"/>
    <material name="work_black_block" rgba="0.06 0.06 0.07 1"/>
    <material name="work_cast_part" rgba="0.30 0.30 0.32 1"/>
    <material name="fixture_steel" rgba="0.55 0.58 0.62 1"/>
    <material name="work_alu_sample" rgba="0.75 0.76 0.80 1"/>
  </asset>
  <worldbody>
    <light pos="0 0 2.0" dir="0 0 -1" diffuse="0.8 0.8 0.8"/>
    <light pos="0.6 -0.6 1.5" dir="-0.4 0.4 -1" diffuse="0.3 0.3 0.3"/>
    <geom name="floor" type="plane" size="2 2 0.1" material="floor_concrete"/>
    <!-- bin: inner 0.40 x 0.30, inner bottom at z = 0.01, top at 0.15 -->
    <!-- thick bottom / walls (rendered inner faces are what the camera sees) so pieces cannot tunnel -->
    <geom name="bin_bottom" type="box" pos="0 0 -0.02" size="0.23 0.18 0.03" material="bin_card"/>
    <geom name="bin_wall_px" type="box" pos="0.22 0 0.08" size="0.02 0.18 0.07" material="bin_card"/>
    <geom name="bin_wall_nx" type="box" pos="-0.22 0 0.08" size="0.02 0.18 0.07" material="bin_card"/>
    <geom name="bin_wall_py" type="box" pos="0 0.17 0.08" size="0.23 0.02 0.07" material="bin_card"/>
    <geom name="bin_wall_ny" type="box" pos="0 -0.17 0.08" size="0.23 0.02 0.07" material="bin_card"/>
    <!-- (MuJoCo euler angles are in degrees) machine fixture with the sample pose of one shaft (lying along y in a V seat) -->
    <geom name="fixture_base" type="box" pos="0.42 0 0.06" size="0.07 0.07 0.06" material="fixture_steel"/>
    <geom name="fixture_v_l" type="box" pos="0.405 0 0.127" euler="0 35 0" size="0.012 0.05 0.008" material="fixture_steel"/>
    <geom name="fixture_v_r" type="box" pos="0.435 0 0.127" euler="0 -35 0" size="0.012 0.05 0.008" material="fixture_steel"/>
    <geom name="sample_shaft" type="cylinder" pos="0.42 0 0.142" euler="90 0 0" size="0.012 0.03" material="work_alu_sample"/>
    <!-- cameras looking down (image right = +x, image down = -y) -->
    <camera name="rs_bin" pos="0.05 0 0.75" xyaxes="1 0 0 0 1 0"/>
    <camera name="rs_near" pos="0 0 0.40" xyaxes="1 0 0 0 1 0"/>
{chr(10).join(bodies)}
  </worldbody>
</mujoco>
"""
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(xml)
    print("wrote", os.path.normpath(OUT), "with", len(bodies), "work pieces")


if __name__ == "__main__":
    main()
